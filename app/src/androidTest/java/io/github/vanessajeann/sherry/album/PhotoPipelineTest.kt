@RunWith(AndroidJUnit4::class)
class PhotoPipelineTest {
    private val instrumentation get() = InstrumentationRegistry.getInstrumentation()
    private val context get() = instrumentation.targetContext

    @Test fun realDecoderRejectsCorruptDataAndHonorsExifAndPanoramaBudget() {
        val directory = File(context.cacheDir, "pipeline-tests").apply { mkdirs() }
        try {
            val bad = File(directory, "broken.heic").apply { writeText("not an image") }
            val decoder = SafePhotoDecoder(context)
            assertNull(decoder.decode(android.net.Uri.fromFile(bad).toString(), 192))
            val panorama = File(directory, "panorama.jpg")
            val bitmap = Bitmap.createBitmap(8192, 32, Bitmap.Config.ARGB_8888)
            bitmap.eraseColor(Color.BLUE)
            panorama.outputStream().use { bitmap.compress(Bitmap.CompressFormat.JPEG, 90, it) }
            bitmap.recycle()
            val decoded = decoder.decode(android.net.Uri.fromFile(panorama).toString(), 192)
            assertNotNull(decoded)
            decoded!!.let { assertTrue(it.width <= 192 && it.height <= 192); assertTrue(it.allocationByteCount <= 192 * 192 * 4); it.recycle() }

            // A real 200 MP file, generated by streaming rows rather than allocating a 200 MP bitmap.
            val large = File(directory, "200mp.png")
            writeLargePng(large, 16000, 12500)
            val small = decoder.decode(android.net.Uri.fromFile(large).toString(), 192)
            assertNotNull(small)
            small!!.let { assertTrue(it.width <= 192 && it.height <= 192); assertTrue(it.allocationByteCount <= 192 * 192 * 4); it.recycle() }

            val rotated = File(directory, "rotated.jpg")
            val source = Bitmap.createBitmap(400, 200, Bitmap.Config.ARGB_8888)
            source.eraseColor(Color.RED)
            rotated.outputStream().use { source.compress(Bitmap.CompressFormat.JPEG, 90, it) }
            source.recycle()
            ExifInterface(rotated).apply { setAttribute(ExifInterface.TAG_ORIENTATION, "6"); saveAttributes() }
            val upright = decoder.decode(android.net.Uri.fromFile(rotated).toString(), 192)
            assertNotNull(upright)
            upright!!.let { assertTrue(it.height > it.width); it.recycle() }
        } finally { directory.listFiles()?.forEach { it.delete() }; directory.delete() }
    }

    @Test fun mediaStoreVisualScanFinishesWithDuplicatesAndCorruptPhoto() = runBlocking {
        if (Build.VERSION.SDK_INT >= 33) instrumentation.uiAutomation.grantRuntimePermission(context.packageName, Manifest.permission.READ_MEDIA_IMAGES)
        val resolver = context.contentResolver
        val prefix = "SherryRegression-${UUID.randomUUID()}"
        val inserted = mutableListOf<android.net.Uri>()
        fun insert(name: String, bytes: ByteArray, mime: String) {
            val uri = resolver.insert(MediaStore.Images.Media.EXTERNAL_CONTENT_URI, ContentValues().apply {
                put(MediaStore.Images.Media.DISPLAY_NAME, "$prefix-$name")
                put(MediaStore.Images.Media.MIME_TYPE, mime)
                if (Build.VERSION.SDK_INT >= 29) { put(MediaStore.Images.Media.RELATIVE_PATH, "Pictures/SherryRegression/"); put(MediaStore.Images.Media.IS_PENDING, 1) }
            })!!
            inserted.add(uri)
            resolver.openOutputStream(uri)!!.use { it.write(bytes) }
            if (Build.VERSION.SDK_INT >= 29) resolver.update(uri, ContentValues().apply { put(MediaStore.Images.Media.IS_PENDING, 0) }, null, null)
        }
        try {
            val bitmap = Bitmap.createBitmap(640, 480, Bitmap.Config.ARGB_8888)
            Canvas(bitmap).apply {
                drawColor(Color.WHITE)
                drawRect(20f, 40f, 340f, 300f, Paint().apply { color = Color.BLUE })
                drawCircle(420f, 170f, 80f, Paint().apply { color = Color.RED })
            }
            val encoded = ByteArrayOutputStream().apply { bitmap.compress(Bitmap.CompressFormat.JPEG, 95, this) }.toByteArray()
            bitmap.recycle()
            insert("first.jpg", encoded, "image/jpeg")
            insert("copy.jpg", encoded, "image/jpeg")
            insert("broken.jpg", byteArrayOf(1, 2, 3, 4), "image/jpeg")
            val stages = mutableListOf<String>()
            val result = PhotoScanner(context).scan(ScanMode.SIMILAR, Sensitivity.BALANCED) { stages.add(it.stage) }
            val duplicate = result.groups.firstOrNull { group -> group.photos.count { it.name.startsWith(prefix) } >= 2 }
            assertNotNull(duplicate)
            assertEquals(GroupKind.EXACT, duplicate!!.kind)
            assertTrue(stages.any { it.contains("画面") })
            assertTrue(result.skipped >= 1)
        } finally { inserted.forEach { resolver.delete(it, null, null) } }
    }

    @Test fun albumScreenStartsAndDiagnosticReportIsAvailable() {
        val activity = instrumentation.startActivitySync(Intent(context, AlbumActivity::class.java).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK))
        try { instrumentation.waitForIdleSync(); assertTrue(ScanDiagnostics.report(context).length() > 0) }
        finally { instrumentation.runOnMainSync { activity.finish() } }
    }

    private fun writeLargePng(file: File, width: Int, height: Int) {
        val row = ByteArray(width * 3 + 1)
        for (x in 0 until width) {
            row[1 + x * 3] = (x % 256).toByte()
            row[2 + x * 3] = 90.toByte()
            row[3 + x * 3] = 160.toByte()
        }
        val compressed = ByteArrayOutputStream()
        DeflaterOutputStream(compressed, Deflater(Deflater.BEST_SPEED)).use { stream -> repeat(height) { stream.write(row) } }
        DataOutputStream(file.outputStream()).use { output ->
            output.write(byteArrayOf(137.toByte(), 80, 78, 71, 13, 10, 26, 10))
            fun chunk(type: String, data: ByteArray) {
                val label = type.toByteArray(Charsets.US_ASCII)
                output.writeInt(data.size); output.write(label); output.write(data)
                val crc = CRC32().apply { update(label); update(data) }
                output.writeInt(crc.value.toInt())
            }
            val header = ByteArrayOutputStream().apply {
                DataOutputStream(this).apply { writeInt(width); writeInt(height); write(byteArrayOf(8, 2, 0, 0, 0)); flush() }
            }.toByteArray()
            chunk("IHDR", header); chunk("IDAT", compressed.toByteArray()); chunk("IEND", byteArrayOf())
        }
    }
}
